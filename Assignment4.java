package practice;

public class Assignment4 //Declare and initialize the variables for all data types
{
	public static void main(String[] args)
	{
		//from here all are local variable
				byte a = 100;//declaration and initialization
				System.out.println(a);//utilization
				short b = 2220;
				System.out.println(b);

				int c = 236545;//declaration and initialization

				System.out.println(c);
				long d = 123456987456l;//declaration and initialization
				System.out.println(d);

				float a1 = 4125.326f;//declaration and initialization
				System.out.println(a1);

				double b2 = 987456321.12345678;//declaration and initialization
				System.out.println(b2);

				char c1 = 'A';//declaration and initialization
				System.out.println(c1);

				boolean d1 = true;//declaration and initialization
				System.out.println(d1);

				String name = "Shreyansh";//declaration and initialization
				System.out.println(name);
				
				int rollno;// declaration
				rollno = 3;//initialization
				System.out.println(rollno);//utilization
	}
}
